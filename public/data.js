// 给每个 {v} 节点分配唯一 key，并收集 seed 列表
function assignKeys(){
  const model = buildModel();
  const seed = [];
  let counter = 0;
  function walk(node, path){
    if(node === null || node === undefined) return;
    if(Array.isArray(node)){
      node.forEach((item, i)=> walk(item, path + '/' + i));
      return;
    }
    if(typeof node === 'object'){
      if('v' in node && typeof node.v === 'string'){
        node.key = 'k' + (counter++);
        seed.push({ key: node.key, value: node.v });
        return;
      }
      for(const k of Object.keys(node)){
        if(k === 'key') continue;
        walk(node[k], path + '/' + k);
      }
    }
  }
  walk(model, 'r');
  return { model, seed };
}

window.__REPORT__ = assignKeys();
